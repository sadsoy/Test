// split.mjs: one narration take -> tightened narration.wav + src/timing.js (line and phrase times for picture and subs).
// Speech phrases come from ffmpeg silencedetect; PHR says how many phrases each script line has in the take.
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync } from 'node:fs';
const SRC = 'out/voice/full.wav', TEMPO = 1.1, LEAD = .15, TAIL = .9, PRE = .04, POST = .05, INNER = .08;
const PHR = [1, 2, 2, 2, 1, 1, 2, 1, 2];
const AFTER = [.35, .3, .3, .3, .15, .4, .35, .3, 0];
const lines = JSON.parse(readFileSync('scripts/lines.json', 'utf8'));
const log = execFileSync('ffmpeg', ['-i', SRC, '-af', 'silencedetect=noise=-38dB:d=0.25', '-f', 'null', '-'], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).toString();
const err = execFileSync('sh', ['-c', `ffmpeg -i ${SRC} -af silencedetect=noise=-38dB:d=0.25 -f null - 2>&1`]).toString();
const st = [...err.matchAll(/silence_start: ([\d.]+)/g)].map(m => +m[1]), en = [...err.matchAll(/silence_end: ([\d.]+)/g)].map(m => +m[1]);
const buf = readFileSync(SRC), sr = buf.readUInt32LE(24), dataAt = buf.indexOf('data') + 8, pcm = new Int16Array(buf.buffer.slice(buf.byteOffset + dataAt));
const dur = pcm.length / sr, segs = [];
for (let i = 0; i < en.length; i++) { const a = en[i], b = i + 1 < st.length ? st[i + 1] : dur; if (b - a > .15) segs.push([a, b]); }
if (segs.length !== PHR.reduce((a, b) => a + b)) { console.error('phrase count mismatch', segs.length); process.exit(1); }
const out = [], push = n => { for (let i = 0; i < n; i++) out.push(0); };
let k = 0; push(Math.round(LEAD * sr * TEMPO));
const TL = { lines: [] };
lines.forEach((L, li) => {
  const ph = [];
  for (let j = 0; j < PHR[li]; j++, k++) {
    const [a, b] = segs[k], s0 = Math.max(0, Math.round((a - PRE) * sr)), s1 = Math.min(pcm.length, Math.round((b + POST) * sr));
    const t0 = out.length / sr; for (let s = s0; s < s1; s++) out.push(pcm[s]); ph.push([t0 + PRE, out.length / sr - POST]);
    if (j < PHR[li] - 1) push(Math.round(INNER * sr * TEMPO));
  }
  TL.lines.push({ id: L.id, text: L.text, t0: ph[0][0], t1: ph[ph.length - 1][1], ph });
  push(Math.round(AFTER[li] * sr * TEMPO));
});
push(Math.round(TAIL * sr * TEMPO));
const raw = Buffer.from(new Int16Array(out).buffer); writeFileSync('out/voice/tight.raw', raw);
execFileSync('ffmpeg', ['-y', '-loglevel', 'error', '-f', 's16le', '-ar', String(sr), '-ac', '1', '-i', 'out/voice/tight.raw', '-af', `atempo=${TEMPO}`, '-ar', '48000', 'out/voice/narration.wav']);
const sc = v => +(v / TEMPO).toFixed(3);
TL.lines.forEach(L => { L.t0 = sc(L.t0); L.t1 = sc(L.t1); L.ph = L.ph.map(p => p.map(sc)); });
TL.duration = +(out.length / sr / TEMPO).toFixed(3);
writeFileSync('src/timing.js', '// generated by scripts/split.mjs: narration line and phrase times (s)\nconst TL = ' + JSON.stringify(TL, null, 1) + ';\nif (typeof module !== "undefined") module.exports = TL;\n');
console.log('duration', TL.duration); TL.lines.forEach(L => console.log(L.id, L.t0, L.t1, L.ph.length));
