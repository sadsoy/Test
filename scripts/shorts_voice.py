"""Place the narration of a Short: split one TTS take into its lines, trim each line's silence, speed it up a little,
and lay the lines on the timeline with set gaps. Writes the narration track and src/shorts/narration.js (line times and
a loudness envelope per frame, for the subtitles and the beats of the animation).

usage: python3 -I scripts/shorts_voice.py <take.wav> <cuts: comma list of approx line starts after the first, s>
Settings below: TEMPO, LEAD (s before the first line), GAP (s before each line), TAIL (s after the last), FPS.
"""
import sys, json, subprocess, struct, wave, math

TAKE, CUTS = sys.argv[1], [float(x) for x in sys.argv[2].split(",")]
LINES = json.load(open("shorts/clean-energy/lines.json"))
TEMPO, LEAD, TAIL, FPS = 1.0, .35, 2.6, 30
GAP = {"n02": .55, "n03": .45, "n04": 1.1, "n05": .6, "n06": 1.1, "n07": .6, "n08": .7, "n09": 1.1, "n10": .8}   # longer before a new act
# a line re-recorded on its own (the take said "ราว" too short): use that file whole instead of the take's span
OVERRIDE = {"n02": "out/shorts/voice/take/n02b.wav"}
OUT_WAV, OUT_JS = "out/shorts/audio/narration.wav", "src/shorts/narration.js"

def pcm(path, sr=24000):
    p = subprocess.run(["ffmpeg", "-loglevel", "error", "-i", path, "-ac", "1", "-ar", str(sr), "-f", "s16le", "-"], capture_output=True)
    return struct.unpack("<%dh" % (len(p.stdout) // 2), p.stdout), sr
x, sr = pcm(TAKE)
def rms(a, b): a, b = max(0, int(a * sr)), min(len(x), int(b * sr)); return (sum(v * v for v in x[a:b]) / max(1, b - a)) ** .5
# refine each cut to the quietest 60 ms within +-0.45 s
cuts = []
for c in CUTS:
    best = min((rms(c + d / 100, c + d / 100 + .06), c + d / 100 + .03) for d in range(-45, 46, 1)); cuts.append(best[1])
bounds = [0] + cuts + [len(x) / sr]
import os; os.makedirs("out/shorts/audio/lines", exist_ok=True)
keys = list(LINES); assert len(keys) == len(bounds) - 1, (len(keys), len(bounds))
segs, t, out = [], LEAD, []
for i, k in enumerate(keys):
    f = f"out/shorts/audio/lines/{k}.wav"
    af = ("silenceremove=start_periods=1:start_threshold=-42dB:start_silence=0.02,areverse,"
          "silenceremove=start_periods=1:start_threshold=-42dB:start_silence=0.06,areverse,"
          f"atempo={TEMPO},afade=t=in:d=0.01")
    src = ["-i", OVERRIDE[k]] if k in OVERRIDE else ["-ss", str(bounds[i]), "-to", str(bounds[i + 1]), "-i", TAKE]
    subprocess.run(["ffmpeg", "-y", "-loglevel", "error", *src, "-af", af, "-ar", "48000", "-ac", "1", f], check=True)
    y, _ = pcm(f, 48000); d = len(y) / 48000
    if i: t += GAP[k]
    env = []
    for n in range(int(math.ceil(d * FPS))):
        a, b = int(n / FPS * 48000), int((n + 1) / FPS * 48000); s = y[a:b]
        v = (sum(q * q for q in s) / max(1, len(s))) ** .5 / 32768; env.append(min(9, max(0, int((20 * math.log10(max(v, 1e-6)) + 52) / 4.4))))
    out.append([round(t, 3), round(t + d, 3), k, LINES[k]["text"], "".join(map(str, env))]); segs.append((f, t)); t += d
dur = round(t + TAIL, 2)
inputs = sum((["-i", f] for f, _ in segs), [])
mix = ";".join(f"[{i}:a]adelay={int(st * 1000)}|{int(st * 1000)}[a{i}]" for i, (_, st) in enumerate(segs))
mix += ";" + "".join(f"[a{i}]" for i in range(len(segs))) + f"amix=inputs={len(segs)}:normalize=0,apad,atrim=0:{dur}[o]"
subprocess.run(["ffmpeg", "-y", "-loglevel", "error", *inputs, "-filter_complex", mix, "-map", "[o]", "-ar", "48000", "-ac", "1", OUT_WAV], check=True)
with open(OUT_JS, "w") as fh:
    fh.write("// narration.js: generated by scripts/shorts_voice.py. NARR = [[start, end, key, text, envelope (0-9 per 1/30 s)], ...]\n")
    fh.write(f"const NARR_DUR = {dur}, NARR_TEMPO = {TEMPO};\nconst NARR = {json.dumps(out, ensure_ascii=False)};\n")
    fh.write("const NT = Object.fromEntries(NARR.map(([a, b, k]) => [k, [a, b]]));\n")
for r in out: print(f"{r[2]} {r[0]:6.2f} {r[1]:6.2f}  {r[3]}")
print("duration", dur, "cuts", [round(c, 2) for c in cuts])
